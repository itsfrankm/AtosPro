CREATE TABLE public.customers (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL,
  document text NOT NULL DEFAULT '',
  whatsapp text NOT NULL DEFAULT '',
  email text NOT NULL DEFAULT '',
  cep text NOT NULL DEFAULT '',
  address text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
GRANT SELECT, INSERT, UPDATE, DELETE ON public.customers TO authenticated;
GRANT ALL ON public.customers TO service_role;
ALTER TABLE public.customers ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Team can read customers" ON public.customers FOR SELECT TO authenticated USING (true);
CREATE POLICY "Team can insert customers" ON public.customers FOR INSERT TO authenticated WITH CHECK (true);
CREATE POLICY "Team can update customers" ON public.customers FOR UPDATE TO authenticated USING (true) WITH CHECK (true);
CREATE POLICY "Team can delete customers" ON public.customers FOR DELETE TO authenticated USING (true);

CREATE TABLE public.service_orders (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  number bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) UNIQUE NOT NULL,
  customer_id uuid NOT NULL REFERENCES public.customers(id) ON DELETE RESTRICT,
  status text NOT NULL DEFAULT 'Em Orçamento',
  entry_date date NOT NULL DEFAULT current_date,
  finish_date date,
  equipment text NOT NULL DEFAULT '',
  brand_model text NOT NULL DEFAULT '',
  serial text NOT NULL DEFAULT '',
  physical_condition text NOT NULL DEFAULT '',
  accessories text NOT NULL DEFAULT '',
  reported_defect text NOT NULL DEFAULT '',
  symptoms text[] NOT NULL DEFAULT '{}',
  technical_report text NOT NULL DEFAULT '',
  technician text NOT NULL DEFAULT '',
  service_done text NOT NULL DEFAULT '',
  parts text NOT NULL DEFAULT '',
  warranty text NOT NULL DEFAULT '90 dias',
  notes text NOT NULL DEFAULT '',
  amount numeric(12,2) NOT NULL DEFAULT 0,
  created_by uuid,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX service_orders_customer_idx ON public.service_orders(customer_id);
GRANT SELECT, INSERT, UPDATE, DELETE ON public.service_orders TO authenticated;
GRANT ALL ON public.service_orders TO service_role;
ALTER TABLE public.service_orders ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Team can read orders" ON public.service_orders FOR SELECT TO authenticated USING (true);
CREATE POLICY "Team can insert orders" ON public.service_orders FOR INSERT TO authenticated WITH CHECK (true);
CREATE POLICY "Team can update orders" ON public.service_orders FOR UPDATE TO authenticated USING (true) WITH CHECK (true);
CREATE POLICY "Team can delete orders" ON public.service_orders FOR DELETE TO authenticated USING (true);

CREATE OR REPLACE FUNCTION public.touch_updated_at() RETURNS trigger LANGUAGE plpgsql SET search_path = public AS $$
BEGIN NEW.updated_at = now(); RETURN NEW; END; $$;
CREATE TRIGGER customers_touch BEFORE UPDATE ON public.customers FOR EACH ROW EXECUTE FUNCTION public.touch_updated_at();
CREATE TRIGGER service_orders_touch BEFORE UPDATE ON public.service_orders FOR EACH ROW EXECUTE FUNCTION public.touch_updated_at();